using System.Collections;
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.UI;

public class UI_ResultTime : MonoBehaviour
{
    // =========================================================
    // 結算時間文字
    // =========================================================

    [Header("結算時間")]

    // 拖入要顯示時間的 UI Text
    public Text timeText;


    // =========================================================
    // 前後文字設定
    // =========================================================

    [Header("顯示文字")]

    // 時間前面的文字
    public string prefixText = "遊戲時間：";

    // 時間後面的文字
    public string suffixText = "";


    // =========================================================
    // 初始化
    // =========================================================

    private void Start()
    {
        UpdateTimeText();
    }


    // =========================================================
    // 更新時間文字
    // =========================================================

    private void UpdateTimeText()
    {
        if (timeText == null)
        {
            return;
        }


        // -----------------------------------------------------
        // 取得 mizuki 記錄的秒數
        // -----------------------------------------------------

        int totalSeconds = mizuki.Time;


        // -----------------------------------------------------
        // 計算分鐘
        // -----------------------------------------------------

        int minutes = totalSeconds / 60;


        // -----------------------------------------------------
        // 計算剩餘秒數
        // -----------------------------------------------------

        int seconds = totalSeconds % 60;


        // -----------------------------------------------------
        // 顯示
        // -----------------------------------------------------
        //
        // 例如：
        //
        // prefixText = "遊戲時間："
        // minutes = 2
        // seconds = 5
        //
        // 顯示：
        // 遊戲時間：02:05
        //
        // -----------------------------------------------------

        timeText.text =
            prefixText +
            minutes.ToString("00") +
            ":" +
            seconds.ToString("00") +
            suffixText;
    }
}
