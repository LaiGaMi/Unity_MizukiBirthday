using UnityEngine;

[RequireComponent(typeof(AudioSource))]
public class VolumeController : MonoBehaviour
{
    // =========================================================
    // 音量類型設定
    // =========================================================

    [Header("音量類型")]

    // true  = 音樂
    // false = 音效
    public bool isMusic = true;


    // =========================================================
    // AudioSource
    // =========================================================

    private AudioSource audioSource;


    // =========================================================
    // 原始音量
    // =========================================================

    // 開始時 AudioSource 的音量
    // 作為 100% 音量基準
    private float baseVolume;


    // =========================================================
    // 初始化
    // =========================================================

    private void Start()
    {
        // -----------------------------------------------------
        // 取得 AudioSource
        // -----------------------------------------------------

        audioSource = GetComponent<AudioSource>();


        // -----------------------------------------------------
        // 記錄開始時的音量
        // -----------------------------------------------------

        baseVolume = audioSource.volume;


        // -----------------------------------------------------
        // 立即套用目前設定
        // -----------------------------------------------------

        UpdateVolume();
    }


    // =========================================================
    // 更新
    // =========================================================

    private void Update()
    {
        // -----------------------------------------------------
        // 即時更新音量
        // -----------------------------------------------------

        UpdateVolume();
    }


    // =========================================================
    // 更新音量
    // =========================================================

    private void UpdateVolume()
    {
        if (audioSource == null)
        {
            return;
        }


        // -----------------------------------------------------
        // 取得目前音量百分比
        // -----------------------------------------------------

        float volumePercent;


        if (isMusic)
        {
            // 音樂音量
            volumePercent = mizuki.musicVolume;
        }
        else
        {
            // 音效音量
            volumePercent = mizuki.seVolume;
        }


        // -----------------------------------------------------
        // 防止超過 0 ~ 1
        // -----------------------------------------------------

        volumePercent =
            Mathf.Clamp01(volumePercent);


        // -----------------------------------------------------
        // 基準音量 × 音量百分比
        // -----------------------------------------------------

        audioSource.volume =
            baseVolume * volumePercent;
    }
}